let language = "zh";
try { language = localStorage.getItem("pulp-language") === "en" ? "en" : "zh"; } catch {}

export function getLanguage() { return language; }

export function t(message, values = {}) {
  const template = language === "en" ? english[message] ?? message : message;
  return template.replace(/\{(\w+)\}/g, (match, key) => values[key] ?? match);
}

export function errorText(error) {
  let message = String(error);
  if (language === "en") {
    for (const key of Object.keys(english).filter((key) => !key.includes("{")).sort((left, right) => right.length - left.length)) {
      message = message.split(key).join(english[key]);
    }
    message = message.replace(/：/g, ": ");
  }
  return message;
}

export function setLanguage(next) {
  language = next === "en" ? "en" : "zh";
  try { localStorage.setItem("pulp-language", language); } catch {}
  document.documentElement.lang = language === "en" ? "en" : "zh-CN";
  for (const element of document.querySelectorAll("[data-i18n]")) {
    element.textContent = t(element.dataset.i18n);
  }
  for (const attribute of ["title", "aria-label", "placeholder"]) {
    for (const element of document.querySelectorAll(`[data-i18n-${attribute}]`)) {
      element.setAttribute(attribute, t(element.getAttribute(`data-i18n-${attribute}`)));
    }
  }
  document.getElementById("preview").dataset.placeholder = t("随手写点什么…");
}
